#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md for the Flutter client from pubspec.lock + the pub cache.

    python3 tools/licenses/gen_notices_client.py [--lock pubspec.lock] [--out THIRD_PARTY_NOTICES.md] [--check]

--check: regenerate to a temp file and fail if it differs from the committed file (CI drift guard).
Only hosted packages are listed (path/git deps are blocked by check_client_licenses.py anyway).
Flutter/Dart SDK and engine notices are NOT generated here: see docs/compliance/third-party-notices.md.
Stdlib only.  Draft - 须律师/法务确认 the exact notice format required.
"""
import argparse, glob, os, re, sys

HEADER = """# THIRD_PARTY_NOTICES

> Generated by tools/licenses/gen_notices_client.py - DO NOT EDIT BY HAND.
> The client itself is licensed under GPL-3.0-only (see LICENSE). This file reproduces the notices of
> third-party Dart/Flutter packages bundled into the app. Packages are listed with the licence text
> shipped in the package itself.

Packages: {n}

"""


def parse_lock(path):
    pkgs, cur, in_pkgs = {}, None, False
    for line in open(path, encoding="utf-8"):
        if line.startswith("packages:"):
            in_pkgs = True
            continue
        if line.startswith("sdks:"):
            in_pkgs = False
        if not in_pkgs:
            continue
        m = re.match(r"^  ([A-Za-z0-9_\-\.]+):\s*$", line)
        if m:
            cur = m.group(1)
            pkgs[cur] = {}
            continue
        m = re.match(r'^    (source|version): "?([^"\n]+)"?\s*$', line)
        if m and cur:
            pkgs[cur][m.group(1)] = m.group(2)
    return pkgs


def render(lock, cache):
    base = os.path.join(cache, "hosted", "pub.dev")
    out, n = [], 0
    for name, meta in sorted(lock.items()):
        if meta.get("source") != "hosted":
            continue
        d = os.path.join(base, f"{name}-{meta['version']}")
        files = sorted(set(glob.glob(os.path.join(d, "LICEN[SC]E*")) + glob.glob(os.path.join(d, "COPYING*")) +
                           glob.glob(os.path.join(d, "NOTICE*"))))
        n += 1
        out.append(f"## {name} {meta['version']}\n\nhttps://pub.dev/packages/{name}/versions/{meta['version']}\n")
        if not files:
            out.append("**NO LICENCE FILE FOUND IN PACKAGE - must be resolved before release.**\n")
        for fp in files:
            out.append(f"### {os.path.basename(fp)}\n\n```text\n{open(fp, encoding='utf-8', errors='replace').read().rstrip()}\n```\n")
    return HEADER.format(n=n) + "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lock", default="pubspec.lock")
    ap.add_argument("--out", default="THIRD_PARTY_NOTICES.md")
    ap.add_argument("--pub-cache")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    cache = a.pub_cache or os.environ.get("PUB_CACHE") or os.path.join(os.path.expanduser("~"), ".pub-cache")
    text = render(parse_lock(a.lock), cache)
    if a.check:
        cur = open(a.out, encoding="utf-8").read() if os.path.exists(a.out) else ""
        if cur != text:
            sys.exit(f"{a.out} is out of date: run tools/licenses/gen_notices_client.py and commit")
        print("notices up to date")
        return
    open(a.out, "w", encoding="utf-8").write(text)
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
